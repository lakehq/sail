use std::collections::HashMap;

use datafusion::logical_expr::LogicalPlan;
use sail_common::spec;

use crate::error::PlanResult;
use crate::resolver::PlanResolver;
use crate::resolver::state::PlanResolverState;

#[derive(Debug)]
pub struct NamedPlan {
    pub plan: LogicalPlan,
    /// The user-facing fields for query plan,
    /// or `None` for a non-query plan (e.g. a DDL statement).
    pub fields: Option<Vec<String>>,
    /// The metadata to add to the user-facing fields of a query plan.
    /// This is the Spark metadata that Spark sets on the names that it generates
    /// for projections, which is not in the logical plan since a projection with
    /// field metadata prevents the physical optimizer from merging projections.
    pub field_metadata: Vec<HashMap<String, String>>,
}

/// The Spark metadata that Spark sets on the name that it generates for a projection.
const AUTO_GENERATED_ALIAS_METADATA: &str = r#"{"__autoGeneratedAlias":"true"}"#;

impl PlanResolver<'_> {
    /// Resolves a plan into a named plan.
    pub async fn resolve_named_plan(&self, plan: spec::Plan) -> PlanResult<NamedPlan> {
        let mut state = PlanResolverState::new();
        match plan {
            spec::Plan::Query(query) => {
                let plan = self.resolve_query_plan(query, &mut state).await?;
                let plan = Self::preserve_order_sensitive_aggregate_sorts(plan)?;
                let fields = Some(Self::get_field_names(plan.schema(), &state)?);
                let field_metadata = plan
                    .schema()
                    .fields()
                    .iter()
                    .map(|field| {
                        Ok(if state.is_auto_generated_alias(field.name())? {
                            HashMap::from([(
                                spec::SPARK_METADATA_JSON_KEY.to_string(),
                                AUTO_GENERATED_ALIAS_METADATA.to_string(),
                            )])
                        } else {
                            HashMap::new()
                        })
                    })
                    .collect::<PlanResult<Vec<_>>>()?;
                Ok(NamedPlan {
                    plan,
                    fields,
                    field_metadata,
                })
            }
            spec::Plan::Command(command) => {
                let plan = self.resolve_command_plan(command, &mut state).await?;
                let plan = Self::preserve_order_sensitive_aggregate_sorts(plan)?;
                Ok(NamedPlan {
                    plan,
                    fields: None,
                    field_metadata: vec![],
                })
            }
        }
    }
}
