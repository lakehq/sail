fn case(input: ScalarFunctionInput) -> PlanResult<expr::Expr> {
    let ScalarFunctionInput {
        arguments,
        function_context,
    } = input;
    let mut conditions = Vec::new();
    let mut branch_values = Vec::new();
    let mut iter = arguments.into_iter();
    while let Some(condition) = iter.next() {
        match iter.next() {
            Some(result) => {
                conditions.push(condition);
                branch_values.push(result);
            }
            _ => {
                conditions.push(lit(true));
                branch_values.push(condition);
                break;
            }
        }
    }
    let branch_values = coerce_string_temporal_values(branch_values, &function_context)?;
    let mut when_then_expr: Vec<_> = conditions
        .into_iter()
        .zip(branch_values)
        .map(|(condition, value)| (Box::new(condition), Box::new(value)))
        .collect();
    // CaseWhen.nullable ignores the missing ELSE when a branch is always
    // true (conditionalExpressions.scala:191-200). A final true branch is an
    // explicit ELSE; moving it preserves every branch's type checking.
    let final_is_true = when_then_expr.last().is_some_and(|(condition, _)| {
        matches!(
            condition.as_ref(),
            expr::Expr::Literal(ScalarValue::Boolean(Some(true)), _)
        )
    });
    let else_expr = if final_is_true {
        when_then_expr.pop().map(|(_, value)| value)
    } else {
        None
    };
    if when_then_expr.is_empty() {
        if let Some(value) = else_expr {
            return Ok(*value);
        }
        return Ok(lit(ScalarValue::Null));
    }
    // Spark's CaseWhen.nullable ORs every branch's nullability unconditionally
    // (conditionalExpressions.scala:191-200) -- including a WHEN branch guarded
    // by a literal-false condition, which can never actually be selected.
    // DataFusion's own `nullable()` excludes such unreachable branches, which
    // disagrees with Spark's declared schema even though both engines compute
    // the same runtime value.
    //
    // Only a literal-boolean WHEN condition can make DataFusion's computation
    // diverge from Spark's (a data-dependent condition is never excluded by
    // either engine, so the two already agree there). Detect that narrow shape
    // directly instead of calling `case_expr.nullable(schema)` to compare: that
    // call also (re-)validates the whole expression tree, including any nested
    // higher-order lambda bodies inside the WHEN conditions -- which defeats
    // Sail's separate mechanism for discarding an unchecked, never-evaluated
    // higher-order return type inside a provably null-typed branch (see
    // "Null-typed predicates discard unchecked higher-order returns" in
    // map_filter.feature) by forcing that validation to run here, too early.
    let has_unreachable_literal_condition = when_then_expr.iter().any(|(condition, _)| {
        matches!(
            condition.as_ref(),
            expr::Expr::Literal(ScalarValue::Boolean(Some(false)), _)
        )
    });
    let schema = function_context.schema;
    let spark_nullable = has_unreachable_literal_condition
        && (when_then_expr
            .iter()
            .any(|(_, value)| value.nullable(schema).unwrap_or(true))
            || else_expr
                .as_ref()
                .is_none_or(|value| value.nullable(schema).unwrap_or(true)));
    let case_expr = expr::Expr::Case(expr::Case {
        expr: None,
        when_then_expr,
        else_expr,
    });
    if spark_nullable {
        // Known to disagree with DataFusion's own `nullable()` precisely
        // because of the literal-false branch just detected -- no need to
        // call it (and risk the same premature-validation side effect) to
        // confirm the disagreement.
        Ok(ScalarUDF::from(SparkForceNullable::new()).call(vec![case_expr]))
    } else {
        Ok(case_expr)
    }
}

fn if_expr(input: ScalarFunctionInput) -> PlanResult<expr::Expr> {
    let ScalarFunctionInput {
        arguments,
        function_context,
    } = input;
    let (when_expr, then_expr, else_expr) = arguments.three()?;
    let (then_expr, else_expr) =
        coerce_string_temporal_values(vec![then_expr, else_expr], &function_context)?.two()?;
    Ok(expr::Expr::Case(expr::Case {
        expr: None,
        when_then_expr: vec![(Box::new(when_expr), Box::new(then_expr))],
        else_expr: Some(Box::new(else_expr)),
    }))
}

fn coalesce(input: ScalarFunctionInput) -> PlanResult<expr::Expr> {
    let ScalarFunctionInput {
        arguments,
        function_context,
    } = input;
    let arguments = coerce_string_temporal_values(arguments, &function_context)?;
    Ok(expr_fn::coalesce(arguments))
}

fn coerce_string_temporal_values(
    arguments: Vec<expr::Expr>,
    function_context: &FunctionContextInput<'_>,
) -> PlanResult<Vec<expr::Expr>> {
    let data_types = arguments
        .iter()
        .map(|arg| arg.get_type(function_context.schema))
        .collect::<Result<Vec<_>, _>>()?;
    let has_string = data_types.iter().any(is_string_type);
    let temporal_type =
        common_temporal_type(&data_types, &function_context.plan_config.session_timezone);
    let arguments = if has_string {
        if let Some(temporal_type) = temporal_type {
            if function_context.plan_config.ansi_mode {
                arguments
                    .into_iter()
                    .zip(data_types.iter())
                    .map(|(arg, data_type)| coerce_to_temporal(arg, data_type, &temporal_type))
                    .collect::<PlanResult<Vec<_>>>()?
            } else {
                arguments
                    .into_iter()
                    .zip(data_types)
                    .map(|(arg, data_type)| {
                        if is_temporal_type(&data_type) {
                            ScalarUDF::from(SparkToUtf8::new()).call(vec![arg])
                        } else {
                            arg
                        }
                    })
                    .collect()
            }
        } else {
            arguments
        }
    } else {
        arguments
    };
    Ok(arguments)
}

fn coerce_to_temporal(
    arg: expr::Expr,
    data_type: &DataType,
    target_type: &DataType,
) -> PlanResult<expr::Expr> {
    if data_type == target_type {
        return Ok(arg);
    }
    if is_string_type(data_type) {
        match target_type {
            DataType::Date32 => Ok(ScalarUDF::from(SparkDate::new(false)).call(vec![arg])),
            // This is only reached when ANSI mode requires a temporal common type.
            DataType::Timestamp(_, timezone) => {
                Ok(
                    ScalarUDF::from(SparkTimestamp::try_new(timezone.clone(), true, false)?)
                        .call(vec![arg]),
                )
            }
            _ => Ok(cast(arg, target_type.clone())),
        }
    } else if is_temporal_type(data_type) {
        Ok(cast(arg, target_type.clone()))
    } else {
        Ok(arg)
    }
}

fn common_temporal_type(data_types: &[DataType], session_timezone: &Arc<str>) -> Option<DataType> {
    if data_types
        .iter()
        .any(|data_type| matches!(data_type, DataType::Timestamp(_, Some(_))))
    {
        Some(DataType::Timestamp(
            TimeUnit::Microsecond,
            Some(Arc::clone(session_timezone)),
        ))
    } else if data_types
        .iter()
        .any(|data_type| matches!(data_type, DataType::Timestamp(_, None)))
    {
        Some(DataType::Timestamp(TimeUnit::Microsecond, None))
    } else {
        data_types
            .iter()
            .any(is_date_type)
            .then_some(DataType::Date32)
    }
}

fn is_string_type(data_type: &DataType) -> bool {
    matches!(
        data_type,
        DataType::Utf8 | DataType::LargeUtf8 | DataType::Utf8View
    )
}

fn is_temporal_type(data_type: &DataType) -> bool {
    is_date_type(data_type) || matches!(data_type, DataType::Timestamp(_, _))
}

fn is_date_type(data_type: &DataType) -> bool {
    matches!(data_type, DataType::Date32 | DataType::Date64)
}

