import pytest
from pyspark.sql import functions as F  # noqa: N812

from pysail.testing.spark.utils.sql import escape_sql_string_literal

# Spark (3.5 and later) sets this metadata on the name that it generates for a projection,
# unless the projection is a column, a field of a column, a cast of a column, a literal,
# or a generator.
AUTO = {"__autoGeneratedAlias": "true"}


def metadata(df):
    return [f.metadata for f in df.schema.fields]


@pytest.fixture(scope="module", autouse=True)
def auto_alias_view(spark):
    spark.sql("SELECT * FROM VALUES (1, named_struct('x', 2)) AS t(a, s)").createOrReplaceTempView("auto_alias")
    yield
    spark.catalog.dropTempView("auto_alias")


# Ported from Spark 3 (3.5.9): pyspark/sql/tests/connect/test_connect_basic.py,
# SparkConnectBasicTests.test_schema, which compares the metadata of the schema.
def test_sql_projection(spark):
    df = spark.sql(
        "SELECT a + 1, a, 1, struct(a) AS st, struct(a), s.x, CAST(a AS STRING), CAST(a + 1 AS STRING) FROM auto_alias"
    )
    assert metadata(df) == [AUTO, {}, {}, {}, AUTO, {}, {}, AUTO]


def test_sql_aggregate_and_window(spark):
    df = spark.sql("SELECT a + 1, sum(a), max(a) AS m FROM auto_alias GROUP BY a + 1")
    assert metadata(df) == [AUTO, AUTO, {}]
    df = spark.sql("SELECT row_number() OVER (ORDER BY a), explode(array(a)) FROM auto_alias")
    assert metadata(df) == [AUTO, {}]


def test_dataframe_projection(spark):
    df = spark.table("auto_alias")
    assert metadata(df.select(F.col("a") + 1, F.lit(1), (F.col("a") + 1).alias("b"))) == [AUTO, {}, {}]
    assert metadata(df.selectExpr("a + 1", "a")) == [AUTO, {}]
    assert metadata(df.groupBy("a").agg(F.sum("a"))) == [{}, AUTO]
    assert metadata(df.withColumn("b", F.col("a") + 1)) == [{}, {}, {}]


def test_subquery_and_union(spark):
    df = spark.sql("SELECT * FROM (SELECT a + 1, sum(a) FROM auto_alias GROUP BY a)")
    assert metadata(df) == [AUTO, AUTO]
    df = spark.sql("SELECT a + 1 FROM auto_alias").select("*")
    assert metadata(df) == [AUTO]

    df = spark.sql("SELECT a AS b FROM auto_alias UNION ALL SELECT a + 2 FROM auto_alias")
    assert metadata(df) == [{}]
    df = spark.sql("SELECT a + 1 FROM auto_alias UNION ALL SELECT a AS b FROM auto_alias")
    assert metadata(df) == [AUTO]


def test_table_does_not_keep_metadata(spark, tmp_path):
    location = escape_sql_string_literal(str(tmp_path / "ctas"))
    query = "SELECT a + 1 FROM auto_alias"
    spark.sql(f"CREATE TABLE auto_alias_ctas USING parquet LOCATION '{location}' AS {query}")
    try:
        assert metadata(spark.table("auto_alias_ctas")) == [{}]
    finally:
        spark.sql("DROP TABLE auto_alias_ctas")
