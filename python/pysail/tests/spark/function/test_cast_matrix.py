# Spark's non-ANSI DOUBLE/FLOAT -> integral cast (`castToByte`/`castToShort`/`castToInt`/
# `castToLong`'s `case x: NumericType =>` branch, Cast.scala:1057 among others) saturates any
# out-of-range value -- not just +-Infinity -- the same way Java's/Scala's `.toInt`/`.toLong`
# do: TINYINT/SMALLINT/INT all go through `.toInt` first (so they share Int32::MAX/MIN as the
# saturated value before TINYINT/SMALLINT narrow it further to their own width, two's-complement
# style), while BIGINT saturates directly via `.toLong` (Int64::MAX/MIN), never through Int32.
@pytest.mark.parametrize(
    ("source", "target", "expected"),
    [
        ("Infinity", "TINYINT", "-1"),
        ("Infinity", "SMALLINT", "-1"),
        ("Infinity", "INT", "2147483647"),
        ("Infinity", "BIGINT", "9223372036854775807"),
        ("-Infinity", "TINYINT", "0"),
        ("-Infinity", "SMALLINT", "0"),
        ("-Infinity", "INT", "-2147483648"),
        ("-Infinity", "BIGINT", "-9223372036854775808"),
        # Same saturating rule for a finite value that merely overflows the target -- not just
        # the +-Infinity edge case above.
        ("1e20", "INT", "2147483647"),
        ("-1e20", "INT", "-2147483648"),
        ("1e20", "BIGINT", "9223372036854775807"),
        ("200.0", "TINYINT", "-56"),
    ],
)
def test_legacy_double_overflow_to_integral_saturates(spark, source, target, expected):
    spark.conf.set("spark.sql.ansi.enabled", "false")
    row = spark.sql(f"SELECT CAST(CAST('{source}' AS DOUBLE) AS {target}) AS v").collect()[0]
    assert _text(row["v"]) == expected


# TIMESTAMP does not need the same treatment: both engines already agree that +-Infinity (and,
# by the same saturating rule, any out-of-range finite DOUBLE) becomes NULL, not a saturated
# epoch value.
def test_legacy_double_infinity_to_timestamp_is_null(spark):
    spark.conf.set("spark.sql.ansi.enabled", "false")
    for source in ("Infinity", "-Infinity"):
        row = spark.sql(f"SELECT CAST(CAST('{source}' AS DOUBLE) AS TIMESTAMP) AS v").collect()[0]
        assert row["v"] is None


# `saturating_double_to_i64` must distinguish an out-of-range non-null value (which Spark
# saturates) from a NULL input (which every Spark CAST propagates). In particular, treating the
# NULL returned by TRY_CAST as the overflow sentinel would turn NULL into the lower bound.
@pytest.mark.parametrize("target", ["TINYINT", "SMALLINT", "INT", "BIGINT"])
def test_legacy_null_double_to_integral_is_null(spark, target):
    spark.conf.set("spark.sql.ansi.enabled", "false")
    row = spark.sql(f"SELECT CAST(CAST(NULL AS DOUBLE) AS {target}) AS v").collect()[0]
    assert row["v"] is None


# Spark's castToDecimal uses toPrecision, which returns NULL in legacy mode on overflow; TRY_CAST
