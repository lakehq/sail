# Type-level (value-independent) rejection shapes Sail/DataFusion/Arrow/parquet-variant raise for
# a pair that cannot be cast at all, recognized as equivalent to any Spark `DATATYPE_MISMATCH.*`
# class. See the module docstring for why this is safe and deliberately narrow.
_UNCASTABLE_PAIR_ALIASES = (
    r"This feature is not implemented: Unsupported CAST from",
    r"invalid argument: cannot cast",
    r"cannot cast \w+ to \w+",
    r"Invalid argument error: Casting .* is not supported",
    r"variant_get: Invalid argument error: Casting .* is not supported",
    r"\[UNSUPPORTED_DATA_TYPE_FOR_ARROW_CONVERSION\]",
)

# A handful of other Spark error classes Sail also reaches for the right reason, but through a
# native message instead of Spark's own class string.
_ERROR_CLASS_ALIASES = {
    "CAST_INVALID_INPUT": (r"invalid \w+:",),
    "NUMERIC_VALUE_OUT_OF_RANGE.WITH_SUGGESTION": (
        r"is too large to store in a Decimal",
        # Sail's own explicit `RaiseError` guard for this class (matching the sibling
        # TIME->Decimal arm's convention) omits the `.WITH_SUGGESTION` subclass suffix.
        r"\[NUMERIC_VALUE_OUT_OF_RANGE\] value out of range for",
    ),
}


def _expected_error_pattern(expected_class):
    """Builds the regex `pytest.raises(match=...)` checks a refused CAST's message against.

    Prefers Spark's own error-class string, but also accepts a handful of known-equivalent
    Sail-native rejection messages (see `_UNCASTABLE_PAIR_ALIASES`/`_ERROR_CLASS_ALIASES`).
    """
    patterns = [re.escape(expected_class)]
    if expected_class.startswith("DATATYPE_MISMATCH."):
        patterns.extend(_UNCASTABLE_PAIR_ALIASES)
    patterns.extend(_ERROR_CLASS_ALIASES.get(expected_class, ()))
    return "|".join(patterns)


