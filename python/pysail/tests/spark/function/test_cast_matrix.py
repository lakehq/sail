"""Every cast Spark allows, and every cast Spark refuses -- 21 source types against 20 targets,
under ANSI on and off.

A cast has two answers and they fail apart: WHETHER the engine takes it at all, and WHAT it
produces. The matrix covers scalar-to-array rejection, interval end-field units, and
integer-to-binary byte order, including combinations a hand-picked list of casts would miss.

Spark's refusals are asserted by their error class, not by their wording: the class is the
contract (`DATATYPE_MISMATCH.CAST_WITHOUT_SUGGESTION` means "this pair is not castable at all",
`CAST_WITH_CONF_SUGGESTION` means "a config would allow it"), the wording is not.

Sail does not yet reproduce Spark's exact `DATATYPE_MISMATCH` class taxonomy for a pair that
cannot be cast at all -- it raises a DataFusion/Arrow/parquet-variant-native rejection instead,
regardless of which of the three "no suggestion" / "func suggestion" / "conf suggestion"
subclasses Spark would pick. `_UNCASTABLE_PAIR_ALIASES` recognizes those native shapes as
satisfying any `DATATYPE_MISMATCH.*` expectation: the CAST *was* correctly refused, only the
class string differs. This is deliberately narrow -- it only matches type-level, value-independent
rejection messages (e.g. "Unsupported CAST from X to Y"), never a value-dependent one (e.g. "Can't
cast value V to type T", which can mean Sail wrongly allows the pair for some other value and only
happens to fail for this one -- those stay real `@sail-bug`s, verified case by case against the
JVM before being excluded here).

`CAST(TIME AS VARIANT)` is left out: the JVM answers it through a py4j wrapper with no error class
to assert. So is every cast whose TARGET is a year-month interval that Spark actually performs:
the PySpark client cannot turn one into a Python object at all, so the answer comes from the
client and no engine ever sees the query.

Every expectation was measured on the Spark 4.2 JVM over Spark Connect with the session zone
pinned to UTC, and values are compared as text so one table serves every client version.

TODO: this file grew case by case (fixing `cast.rs` bugs one at a time, each one measured then
removed from the table) rather than by design, so it now holds two plain literal tables
(`MATRIX`, `ANSI_OFF`) as positional tuples. A structured record per case (e.g. a small
dataclass or namedtuple carrying src/dst/ansi/expected) would make future edits less fragile
than positional tuples, though it is no longer urgent now that no known bug remains (every row
that once diverged has been fixed and folded back into the plain tables) instead of the
hundreds this file once tracked.
"""

