@pytest.fixture(autouse=True)
def _session(spark):
    """Pin the zone and open the TIME type; restore whatever the session had."""
    keys = ("spark.sql.session.timeZone", "spark.sql.timeType.enabled", "spark.sql.ansi.enabled")
    previous = {}
    for key in keys:
        try:
            previous[key] = spark.conf.get(key)
        except Exception:  # noqa: BLE001
            previous[key] = None
    spark.conf.set("spark.sql.session.timeZone", "UTC")
    with contextlib.suppress(Exception):
        spark.conf.set("spark.sql.timeType.enabled", "true")
    yield
    for key, value in previous.items():
        if value is not None:
            with contextlib.suppress(Exception):
                spark.conf.set(key, value)


def _text(value):
    """`bytes` and `bytearray` print differently, and which one the client returns changed in
    PySpark 4.1; normalising keeps one expectation good for every client version."""
    if isinstance(value, bytearray):
        value = bytes(value)
    return "NULL" if value is None else str(value)[:40]


