"""Every cast Spark allows, and every cast Spark refuses -- 21 source types against 20 targets,
under ANSI on and off.

A cast has two answers and they fail apart: WHETHER the engine takes it at all, and WHAT it
produces. Sail turns any scalar into a one-element array, reads an INTERVAL DAY as its
microseconds where Spark reads its days, and writes an INT to BINARY little-endian where Spark
writes it big-endian -- none of which a hand-picked list of casts would have reached.

Spark's refusals are asserted by their error class, not by their wording: the class is the
contract (`DATATYPE_MISMATCH.CAST_WITHOUT_SUGGESTION` means "this pair is not castable at all",
`CAST_WITH_CONF_SUGGESTION` means "a config would allow it"), the wording is not.

`CAST(TIME AS VARIANT)` is left out: the JVM answers it through a py4j wrapper with no error class
to assert. So is every cast whose TARGET is a year-month interval that Spark actually performs:
the PySpark client cannot turn one into a Python object at all, so the answer comes from the
client and no engine ever sees the query.

Every expectation was measured on the Spark 4.2 JVM over Spark Connect with the session zone
pinned to UTC, and values are compared as text so one table serves every client version.
"""

