def _text(value):
    """`bytes` and `bytearray` print differently, and which one the client returns changed in
    PySpark 4.1; normalising keeps one expectation good for every client version."""
    if isinstance(value, bytearray):
        value = bytes(value)
    return "NULL" if value is None else str(value)[:40]


