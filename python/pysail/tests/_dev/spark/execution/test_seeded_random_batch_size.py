@pytest.fixture(scope="module", params=["local", "local-cluster"])
def remote(request):
    envs = {
        "SAIL_MODE": request.param,
        "SAIL_EXECUTION__BATCH_SIZE": "4",
    }
    with spark_connect_server(envs=envs) as server:
        yield server.remote


def test_seeded_random_values_continue_across_batches(spark):
    rows = spark.sql("SELECT id, rand(42) AS r, randn(42) AS n FROM range(0, 40, 1, 4) ORDER BY id").collect()
    assert [tuple(row) for row in rows] == EXPECTED
